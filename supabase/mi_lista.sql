create table if not exists public.mi_lista (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  tmdb_id integer not null,
  titulo text not null,
  poster_url text,
  tipo_contenido text not null,
  estado text not null,
  calificacion_personal integer,
  comentario text,
  fecha_agregado timestamptz not null default now(),
  constraint mi_lista_tmdb_id_positivo check (tmdb_id > 0),
  constraint mi_lista_titulo_no_vacio check (char_length(btrim(titulo)) > 0),
  constraint mi_lista_tipo_contenido_valido check (tipo_contenido in ('pelicula', 'serie')),
  constraint mi_lista_estado_valido check (estado in ('por_ver', 'viendo', 'vista')),
  constraint mi_lista_calificacion_rango check (
    calificacion_personal is null
    or (calificacion_personal >= 1 and calificacion_personal <= 5)
  ),
  constraint mi_lista_comentario_longitud check (
    comentario is null or char_length(comentario) <= 2000
  ),
  -- TMDB reutiliza números entre películas y series. El requisito pide unicidad
  -- solo por usuario e identificador, así que un mismo número no puede guardarse
  -- dos veces aunque el tipo de contenido sea distinto.
  constraint mi_lista_usuario_tmdb_unico unique (user_id, tmdb_id)
);

create index if not exists mi_lista_usuario_fecha_idx
  on public.mi_lista (user_id, fecha_agregado desc);

alter table public.mi_lista enable row level security;

revoke all on table public.mi_lista from public, anon;
grant select, insert, update, delete on table public.mi_lista to authenticated;

drop policy if exists mi_lista_select_propios on public.mi_lista;
create policy mi_lista_select_propios
  on public.mi_lista
  for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists mi_lista_insert_propios on public.mi_lista;
create policy mi_lista_insert_propios
  on public.mi_lista
  for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists mi_lista_update_propios on public.mi_lista;
create policy mi_lista_update_propios
  on public.mi_lista
  for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists mi_lista_delete_propios on public.mi_lista;
create policy mi_lista_delete_propios
  on public.mi_lista
  for delete
  to authenticated
  using (auth.uid() = user_id);

-- No hay políticas para el rol anon: sin sesión, RLS rechaza cualquier acceso.
