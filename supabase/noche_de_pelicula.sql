create table if not exists public.noche_sesion (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nombre text not null,
  tiempo_disponible_minutos integer not null,
  fecha_guardada timestamptz not null default now(),
  constraint noche_sesion_nombre check (
    char_length(btrim(nombre)) > 0 and char_length(btrim(nombre)) <= 80
  ),
  constraint noche_sesion_tiempo check (
    tiempo_disponible_minutos between 30 and 600
  )
);

create table if not exists public.noche_sesion_pelicula (
  id bigint generated by default as identity primary key,
  sesion_id bigint not null references public.noche_sesion (id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  tmdb_id integer not null,
  titulo text not null,
  duracion_minutos integer not null,
  poster_url text,
  orden integer not null,
  constraint noche_pelicula_tmdb check (tmdb_id > 0),
  constraint noche_pelicula_titulo check (char_length(btrim(titulo)) > 0),
  constraint noche_pelicula_duracion check (duracion_minutos > 0),
  constraint noche_pelicula_orden check (orden > 0),
  constraint noche_pelicula_unica unique (sesion_id, tmdb_id),
  constraint noche_pelicula_orden_unico unique (sesion_id, orden)
);

alter table public.noche_sesion enable row level security;
alter table public.noche_sesion_pelicula enable row level security;

revoke all on public.noche_sesion, public.noche_sesion_pelicula from public, anon;
grant select, insert, update, delete on public.noche_sesion, public.noche_sesion_pelicula to authenticated;

grant usage, select on sequence public.noche_sesion_id_seq to authenticated;
grant usage, select on sequence public.noche_sesion_pelicula_id_seq to authenticated;

drop policy if exists noche_sesion_select on public.noche_sesion;
create policy noche_sesion_select on public.noche_sesion
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists noche_sesion_insert on public.noche_sesion;
create policy noche_sesion_insert on public.noche_sesion
  for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists noche_sesion_update on public.noche_sesion;
create policy noche_sesion_update on public.noche_sesion
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists noche_sesion_delete on public.noche_sesion;
create policy noche_sesion_delete on public.noche_sesion
  for delete to authenticated using (auth.uid() = user_id);

drop policy if exists noche_pelicula_select on public.noche_sesion_pelicula;
create policy noche_pelicula_select on public.noche_sesion_pelicula
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists noche_pelicula_insert on public.noche_sesion_pelicula;
create policy noche_pelicula_insert on public.noche_sesion_pelicula
  for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists noche_pelicula_update on public.noche_sesion_pelicula;
create policy noche_pelicula_update on public.noche_sesion_pelicula
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists noche_pelicula_delete on public.noche_sesion_pelicula;
create policy noche_pelicula_delete on public.noche_sesion_pelicula
  for delete to authenticated using (auth.uid() = user_id);
